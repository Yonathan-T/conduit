package convert

import (
	"conduit/internal/model"
	"errors"
	"fmt"
	"strings"
)

func GenerateProto(api *model.API) (string, error) {
	if api == nil {
		return "", errors.New("api is nil")
	}

	var b strings.Builder

	b.WriteString("// Code generated by Conduit. \n")
	b.WriteString("syntax = \"proto3\";\n\n")
	if api.Package != "" {
		b.WriteString(fmt.Sprintf("package %s;\n\n", api.Package))
		pkgPath := strings.ReplaceAll(api.Package, ".", "/")
		pkgAlias := strings.ReplaceAll(api.Package, ".", "")
		b.WriteString(fmt.Sprintf("option go_package = \"conduit/generated/%s;%s\";\n\n", pkgPath, pkgAlias))
	}

	for _, svc := range api.Services {
		b.WriteString(fmt.Sprintf("service %s {\n", svc.Name))
		for _, m := range svc.Methods {
			b.WriteString(fmt.Sprintf("  rpc %s (%s) returns (%s);\n",
				m.Name, m.Request.Name, m.Response.Name))
		}
		b.WriteString("}\n\n")
	}

	seen := make(map[string]bool)
	writeUniqueMessage := func(msg *model.Message) {
		if msg != nil && !seen[msg.Name] {
			seen[msg.Name] = true
			writeMessage(&b, msg)
		}
	}

	for _, svc := range api.Services {
		for _, m := range svc.Methods {
			writeUniqueMessage(&m.Request)
			writeUniqueMessage(&m.Response)
		}
	}

	for i := range api.Types {
		writeUniqueMessage(&api.Types[i])
	}

	return b.String(), nil
}

func protoType(t string) string {
	if strings.HasSuffix(t, "[]") {
		base := strings.TrimSuffix(t, "[]")
		return "repeated " + protoType(base)
	}
	return t
}

func writeMessage(b *strings.Builder, msg *model.Message) {
	if msg == nil {
		return
	}

	b.WriteString(fmt.Sprintf("message %s {\n", msg.Name))
	for i, f := range msg.Fields {
		tag := f.Tag
		if tag == 0 {
			tag = i + 1
		}
		b.WriteString(fmt.Sprintf("  %s %s = %d;\n", protoType(f.Type), f.Name, tag))
	}
	b.WriteString("}\n\n")
}
